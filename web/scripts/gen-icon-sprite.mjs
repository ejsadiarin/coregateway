// Generates src/pages/dashboard/draw/icon-sprite.generated.ts from the
// hand-authored icon-catalog.json.
//
// Why a generator instead of an icon dependency: the catalog is the source of
// truth, and the sprite is committed so the browser never calls a CDN and the
// draw chunk stays self-contained. Re-run with `pnpm icons:gen` after editing
// the catalog.
//
// Source: Iconify (https://iconify.design). Each family names an Iconify
// collection ("prefix"); we fetch the SVG bodies in bulk and store them keyed
// by "<prefix>:<name>". Icons retain their original vendor colours.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const webRoot = resolve(here, "..");
const catalogPath = resolve(webRoot, "src/pages/dashboard/draw/icon-catalog.json");
const outPath = resolve(webRoot, "src/pages/dashboard/draw/icon-sprite.generated.ts");

const catalog = JSON.parse(readFileSync(catalogPath, "utf8"));

// Group requested icon names by their Iconify collection prefix.
const byPrefix = new Map();
for (const family of catalog.families) {
  const prefix = family.prefix;
  if (!byPrefix.has(prefix)) byPrefix.set(prefix, new Set());
  for (const icon of family.icons) {
    const p = icon.prefix ?? prefix;
    if (!byPrefix.has(p)) byPrefix.set(p, new Set());
    byPrefix.get(p).add(icon.name);
  }
}

async function fetchCollection(prefix, names) {
  const url = `https://api.iconify.design/${prefix}.json?icons=${encodeURIComponent([...names].join(","))}`;
  const res = await fetch(url, {
    headers: { "User-Agent": "coredraw-icon-sprite-generator" },
  });
  if (!res.ok) throw new Error(`Iconify ${prefix}: HTTP ${res.status}`);
  return res.json();
}

const sprite = {};
const missing = [];

for (const [prefix, names] of byPrefix) {
  const data = await fetchCollection(prefix, names);
  const topW = data.width ?? 16;
  const topH = data.height ?? 16;
  for (const name of names) {
    const icon = data.icons?.[name];
    if (!icon) {
      missing.push(`${prefix}:${name}`);
      continue;
    }
    const w = icon.width ?? topW;
    const h = icon.height ?? topH;
    sprite[`${prefix}:${name}`] = { viewBox: `0 0 ${w} ${h}`, body: icon.body };
  }
}

if (missing.length) {
  console.error(`Missing ${missing.length} icon(s):\n  ${missing.join("\n  ")}`);
  process.exitCode = 1;
}

const ids = Object.keys(sprite).sort();
const lines = ids.map(
  (id) => `  ${JSON.stringify(id)}: { viewBox: ${JSON.stringify(sprite[id].viewBox)}, body: ${JSON.stringify(sprite[id].body)} },`,
);

const out = `// AUTO-GENERATED by scripts/gen-icon-sprite.mjs — do not edit by hand.
// Source: Iconify (https://iconify.design). ${ids.length} icons.
// Regenerate with: pnpm icons:gen

export interface SpriteIcon {
  viewBox: string;
  body: string;
}

export const ICON_SPRITE: Record<string, SpriteIcon> = {
${lines.join("\n")}
};
`;

writeFileSync(outPath, out);
console.log(`Wrote ${ids.length} icons to ${outPath}`);
